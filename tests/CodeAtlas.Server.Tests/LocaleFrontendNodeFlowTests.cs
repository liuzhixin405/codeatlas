using System.Reflection;

namespace CodeAtlas.Server.Tests;

/// <summary>
/// 框架流程 · 前端（React / Next.js）与 Node（Express / Koa / NestJS）的英文输出：阶段名、节点标签（Nest 的 "控制器" → "Controllers"，与扩展的约定）、
/// Note、Notes 都是英文且没有中文残留；靠文字驱动的逻辑（"没认出请求封装" 去重、QueryCache / MutationCache 合并时的替换、Koa 的 catch 统计）在英文下照样成立。
/// 夹具复用 FrontendFrameworkFlowTests / NodeFrameworkFlowTests 的（私有静态方法，反射取）。
/// </summary>
[Collection("Locale")]
public class LocaleFrontendNodeFlowTests
{
    private const BindingFlags Private = BindingFlags.NonPublic | BindingFlags.Static;

    private static FrameworkInput Frontend(string fixture) =>
        (FrameworkInput)typeof(FrontendFrameworkFlowTests).GetMethod(fixture, Private)!.Invoke(null, null)!;

    private static FrameworkInput Node(string fixture)
    {
        var fx = typeof(NodeFrameworkFlowTests).GetMethod(fixture, Private)!.Invoke(null, null)!;
        return (FrameworkInput)fx.GetType().GetMethod("Input")!.Invoke(fx, null)!;
    }

    private static List<FlowNodeDto> All(FlowNodeDto n) => [n, .. n.Children.SelectMany(All)];

    private static void NoChinese(FrameworkFlowDto f)
    {
        Assert.DoesNotMatch("[一-鿿]", f.Flow.EntryLabel);
        Assert.All(f.Stages, s => Assert.DoesNotMatch("[一-鿿]", s.Label));
        Assert.All(f.Flow.Actors, a => Assert.DoesNotMatch("[一-鿿]", a.Label));
        Assert.All(All(f.Flow.Root), n =>
        {
            Assert.DoesNotMatch("[一-鿿]", n.Label);
            Assert.DoesNotMatch("[一-鿿]", n.Note ?? "");
        });
        Assert.All(f.Notes, n => Assert.DoesNotMatch("[一-鿿]", n));
    }

    // ================= 前端 =================

    [Fact]
    public void Next_flow_in_english_request_wrapper_note_not_duplicated()
    {
        using var _ = Loc.Use("en");
        var f = FrontendFrameworkFlow.Build(Frontend("NextFixture"));

        Assert.Equal(["Routing", "Mount", "Provider", "Pages", "Teardown"], f.Stages.Select(s => s.Label));
        Assert.Equal("Page load", f.Flow.Root.Label);
        Assert.Equal(["middleware (middleware.ts)", "RootLayout", "Providers", "QueryClientProvider", "SessionProvider", "ShopLayout", "Pages"],
            f.Flow.Root.Children.Select(c => c.Label));
        Assert.Equal("Next middleware (middleware.ts): every request passes through it on the server before layouts render; matcher = [\"/((?!api|_next).*)\"]; "
                     + "Guard: redirects to /login (NextResponse.redirect) when !session", f.Flow.Root.Children[0].Note);
        Assert.Equal("Layout app/layout.tsx: wraps 3/3 pages", f.Flow.Root.Children[1].Note);
        Assert.Contains("via Providers", f.Flow.Root.Children[3].Note);
        var error = Assert.Single(f.Flow.Root.Children.Single(c => c.Kind == "controllers").Children);
        Assert.Equal("error.tsx (app)", error.Label);
        Assert.Contains(f.Notes, n => n.StartsWith("Mount: Next.js App Router has no createRoot", StringComparison.Ordinal)
                                      && n.EndsWith("drew 2 layouts that wrap at least half of the pages (1 more local layout wraps only a few pages; not drawn)", StringComparison.Ordinal));

        // 产生处（服务端 axios 那条）与收尾时的去重判断共用同一个前缀：英文下也只有一条
        Assert.Equal("Request wrapper not recognized: the page side has no axios.create / interceptors / generated client / fetch wrapper; "
                     + "1 more axios instance lives in server-side API routes / middleware (not on the page request path; not drawn)",
            Assert.Single(f.Notes, n => n.StartsWith("Request wrapper not recognized", StringComparison.Ordinal)));
        NoChinese(f);
    }

    [Fact]
    public void TanStack_flow_in_english_query_and_mutation_onError_merged()
    {
        using var _ = Loc.Use("en");
        var f = FrontendFrameworkFlow.Build(Frontend("ShopFixture"));
        var page = f.Flow.Root.Children.Single(c => c.Kind == "controllers");

        Assert.Equal("Pages", page.Label);
        Assert.Equal(["client (generated client)", "QueryCache.onError / MutationCache.onError → handleApiError", "ErrorBoundary", "errorComponent → ErrorPage"],
            page.Children.Select(c => c.Label));
        Assert.StartsWith("OpenAPI client generated by @hey-api/openapi-ts (client.gen.ts:", page.Children[0].Note);
        Assert.Contains("client.setConfig (baseURL, auth)", page.Children[0].Note);
        Assert.EndsWith("; token: the auth / TOKEN in the config is attached to every request; no interceptors registered", page.Children[0].Note);
        // 同一个函数挂在 QueryCache 与 MutationCache 上：合并时把 "on query error" 换成 "on query / mutation error"
        Assert.Equal("TanStack Query global: on query / mutation error: involves 401/403; clear access_token, redirect to /login", page.Children[1].Note);
        Assert.StartsWith("On render error: ErrorBoundary (main.tsx:", page.Children[2].Note);
        Assert.EndsWith(") shows a fallback UI", page.Children[2].Note);
        Assert.Contains("Shown on route error (__root.tsx:", page.Children[3].Note);
        Assert.Contains(f.Notes, n => n.StartsWith("Pages: Entry discovery registered no pages", StringComparison.Ordinal));
        NoChinese(f);
    }

    [Fact]
    public void ReactRouter_flow_in_english_guard_and_error_handling()
    {
        using var _ = Loc.Use("en");
        var f = FrontendFrameworkFlow.Build(Frontend("AcmeFixture"));
        var routes = f.Flow.Root.Children.Where(c => c.Actor == "route").ToList();

        Assert.Matches(@"^React Router route table \(App\.jsx:\d+\): 4 routes, 1 layout route$", routes[1].Note);
        var layout = Assert.Single(routes[1].Children);
        Assert.Equal("Layout route (no path)", layout.Label);
        Assert.StartsWith("wraps 2 child routes: /, /orders", layout.Note);
        Assert.Equal("Guard: redirects to /login (Navigate) when !user", layout.Children[0].Note);
        Assert.Equal("Layout component: child routes render at <Outlet/>", layout.Children[1].Note);

        var page = f.Flow.Root.Children.Single(c => c.Kind == "controllers");
        Assert.Equal(["axios.create", "http.interceptors.request.use", "http.interceptors.response.use (success)", "http.interceptors.response.use (error)"],
            page.Children.Select(c => c.Label));
        Assert.Matches(@"^axios instance \(http\.js:\d+\): baseURL, timeout$", page.Children[0].Note);
        Assert.Matches(@"^Request interceptor \(http\.js:\d+\): runs before every request is sent; sets headers Authorization$", page.Children[1].Note);
        Assert.EndsWith("; on success, unwraps response.data for the caller", page.Children[2].Note);
        Assert.Matches(@"^On response error \(http\.js:\d+\): involves 401; clear token, redirect to /login, show an error toast, rethrow to the caller$", page.Children[3].Note);
        Assert.Equal(["removeItem"], page.Children[3].Children.Select(c => c.Label));
        Assert.Contains(f.Notes, n => n == "Request wrapper: 1 axios instance; 1 request interceptor; 2 response interceptors (in teardown)");
        NoChinese(f);
    }

    // ================= Node =================

    [Fact]
    public void Nest_flow_in_english_controllers_label()
    {
        using var _ = Loc.Use("en");
        var f = FrameworkFlowBuilder.Build(Node("NestFixture"));

        Assert.Equal(["Middleware", "Guards", "Interceptors", "Pipes", "Controllers", "Teardown"], f.Stages.Select(s => s.Label));
        var root = f.Flow.Root;
        Assert.Equal(("HTTP request", "middleware"), (root.Label, root.Actor));
        Assert.Equal("third-party middleware (helmet) (main.ts:13)", root.Children[0].Note);
        Assert.Equal("Nest built-in (main.ts:15)", root.Children[2].Note);
        Assert.Equal("Module middleware (app.module.ts:23, forRoutes *, exclude 1)", root.Children[3].Note);
        Assert.Contains("Conditional", root.Children[4].Note);
        Assert.Equal("useGlobalGuards (main.ts:16)", root.Children[5].Note);
        Assert.Equal("APP_GUARD provider (app.module.ts:14)", root.Children[6].Note);
        Assert.Equal("Nest built-in / third-party (useGlobalPipes (main.ts:18))", root.Children[9].Note);

        // 与扩展的约定：控制器占位的标签英文下就是 "Controllers"
        var ctrl = root.Children[11];
        Assert.Equal(("controllers", 2, "Controllers"), (ctrl.Kind, ctrl.Count, ctrl.Label));
        Assert.Equal("TimeoutInterceptor after next.handle()", ctrl.Children[0].Note);
        Assert.Equal("LoggingInterceptor after next.handle() · in a callback / lambda", ctrl.Children[4].Note);
        Assert.Equal("On error (exception filter, useGlobalFilters (main.ts:19)); @Catch() catches all exceptions", ctrl.Children[5].Note);
        Assert.Equal("On error (exception filter, APP_FILTER provider (app.module.ts:17)); catches only HttpException", ctrl.Children[6].Note);

        Assert.Equal("Recognized NestJS (app = await NestFactory.create(AppModule) at main.ts:11); global prefix /api", f.Notes[0]);
        Assert.StartsWith("Order follows Nest's fixed request lifecycle: middleware → guards → interceptors (before)", f.Notes[1]);
        Assert.Contains(f.Notes, n => n == "Controller / method level: @UseGuards in 2 places (OwnerGuard, ThrottlerGuard), @UseInterceptors in 1 place (IdempotencyInterceptor)"
                                           + " — applies only to that controller / method; not drawn in the skeleton");
        NoChinese(f);
    }

    [Fact]
    public void Express_flow_in_english()
    {
        using var _ = Loc.Use("en");
        var f = FrameworkFlowBuilder.Build(Node("ExpressFixture"));

        Assert.Equal(["Middleware", "Routes", "Teardown"], f.Stages.Select(s => s.Label));
        var root = f.Flow.Root;
        Assert.Equal("HTTP request", root.Label);
        Assert.Equal(["helmet", "cors", "express.json", "requestId", "requestLogger", "hpp", "verifyApiKey", "app.use (inline middleware)", "rateLimit()", "Routes"],
            root.Children.Select(c => c.Label));
        Assert.Equal("third-party middleware (helmet) (app.js:17)", root.Children[0].Note);
        Assert.Equal("Express built-in (app.js:21)", root.Children[2].Note);
        Assert.Equal("custom middleware (app.js:22)", root.Children[3].Note);
        Assert.Equal("via registerSecurity(); third-party middleware (hpp) (security.js:6)", root.Children[5].Note);
        Assert.Contains("applies only to /api (app.js:33)", root.Children[8].Note);
        Assert.Contains("registered after GET /health", root.Children[8].Note);

        var routes = root.Children[9];
        Assert.Equal(["Mount /api (apiRouter)", "metrics.inFlight", "notFound", "errorHandler", "logger.info"], routes.Children.Select(c => c.Label));
        var mount = routes.Children[0];
        Assert.Equal("Route mount (app.js:33)", mount.Note);
        Assert.Equal("router-level middleware (applies only to routes under /api, index.js:8)", mount.Children[0].Note);
        Assert.Equal("Route mount (index.js:9): 2 routes in orders.js", mount.Children[1].Note);
        Assert.Equal("app.use (inline middleware) after", routes.Children[1].Note);
        Assert.StartsWith("Registered after the routes (app.js:34)", routes.Children[2].Note);
        Assert.Contains("(404 fallback)", routes.Children[2].Note);
        Assert.Equal("On error (four-argument error middleware, app.js:35)", routes.Children[3].Note);
        Assert.Equal("requestLogger: once the response has been sent (res.on('finish')) · in a callback / lambda", routes.Children[4].Note);

        Assert.Equal("Recognized Express (app = express() at app.js:14)", f.Notes[0]);
        Assert.Contains(f.Notes, n => n == "On error: errorHandler (four-argument error middleware, in registration order)");
        NoChinese(f);
    }

